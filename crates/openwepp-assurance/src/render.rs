pub(crate) const GENERATED_MARKER: &str = "Generated by openwepp-assurance; DO NOT EDIT";

pub(crate) fn render_index(
    template: &str,
    catalog: &Catalog,
    bundles: &[Bundle],
) -> Result<String> {
    let rows = bundles
        .iter()
        .map(|bundle| {
            format!(
                "- [{}]({}) — `{}` / `{}` as of {}; \
                 [method]({}) and [model narrative]({}).",
                bundle.dossier.title,
                relative_link(&catalog.shared_outputs.index, &bundle.entry.outputs.dossier),
                bundle.dossier.lifecycle.label(),
                bundle.dossier.empirical.label(),
                bundle.dossier.evidence_as_of,
                relative_link(&catalog.shared_outputs.index, &bundle.entry.outputs.method),
                relative_link(
                    &catalog.shared_outputs.index,
                    &Path::new("usersum").join(&bundle.dossier.narrative.path)
                )
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    replace_template(template, &[(&"DOSSIER_ROWS", rows)])
}

pub(crate) fn render_method(template: &str, bundle: &Bundle) -> Result<String> {
    let values = vec![
        ("SOURCE_PATH", bundle.entry.method.display().to_string()),
        ("TITLE", bundle.method.title.clone()),
        ("METHOD_ID", bundle.method.method_id.clone()),
        ("VERSION", bundle.method.version.clone()),
        ("DESIGN", bundle.method.design.label().to_owned()),
        ("OWNER", bundle.method.owner.clone()),
        ("QUESTION", bundle.method.question.clone()),
        ("QUANTITIES", bullets(&bundle.method.quantities)),
        ("DOMAIN", bullets(&bundle.method.domain)),
        ("DATASETS", bullets(&bundle.method.datasets)),
        ("METRICS", bullets(&bundle.method.metrics)),
        ("CRITERIA", bullets(&bundle.method.criteria)),
        ("UNCERTAINTY", bullets(&bundle.method.uncertainty)),
        ("REPRODUCTION", bullets(&bundle.method.reproduction)),
        (
            "DOSSIER_LINK",
            relative_link(&bundle.entry.outputs.method, &bundle.entry.outputs.dossier),
        ),
    ];
    replace_template(template, &values)
}

