mod tests {
    use super::downstream_status;
    use crate::model::Lifecycle;

    #[test]
    fn downstream_status_maps_every_assurance_lifecycle() {
        assert_eq!(downstream_status(Lifecycle::Draft), "draft");
        assert_eq!(downstream_status(Lifecycle::Candidate), "active");
        assert_eq!(downstream_status(Lifecycle::Published), "active");
        assert_eq!(downstream_status(Lifecycle::Superseded), "deprecated");
        assert_eq!(downstream_status(Lifecycle::Withdrawn), "deprecated");
    }
}
